  const root = document.documentElement;
  const langToggle = document.getElementById('lang-toggle');
  const themeToggle = document.getElementById('theme-toggle');
  const navToggle = document.getElementById('nav-toggle');

  const applyLang = lang => {
    root.setAttribute('lang', lang);
    document.title = translations[lang]['meta.title'];
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (translations[lang][key] !== undefined) el.textContent = translations[lang][key];
    });
    document.querySelectorAll('[data-i18n-alt]').forEach(el => {
      const key = el.getAttribute('data-i18n-alt');
      if (translations[lang][key] !== undefined) el.setAttribute('alt', translations[lang][key]);
    });
    langToggle.textContent = lang === 'es' ? 'EN' : 'ES';
    langToggle.setAttribute('aria-label', translations[lang]['a11y.lang']);
    themeToggle.setAttribute('aria-label', translations[lang]['a11y.theme']);
    navToggle.setAttribute('aria-label', translations[lang]['a11y.nav']);
    document.getElementById('exp-prev').setAttribute('aria-label', translations[lang]['a11y.prev']);
    document.getElementById('exp-next').setAttribute('aria-label', translations[lang]['a11y.next']);
  };

  const browserLang = (navigator.language || 'es').toLowerCase().startsWith('en') ? 'en' : 'es';
  const initialLang = localStorage.getItem('lang') || browserLang;
  applyLang(initialLang);

  langToggle.addEventListener('click', () => {
    const next = root.getAttribute('lang') === 'es' ? 'en' : 'es';
    applyLang(next);
    localStorage.setItem('lang', next);
  });
